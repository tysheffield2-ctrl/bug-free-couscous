import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {harness} from './harness.mjs';
const h=harness('/offline');
h.run('s=migrateSaveState(s);s.started=true;saveReady=true');
assert.match(h.run('artistFilePage()'),/onclick="V129_open\(\)"/);
assert.equal(h.run('s.appearance'),undefined);
assert.deepEqual(JSON.parse(h.run('JSON.stringify([V129_SKINS.length,V129_HAIRS.length,V129_STYLES.length,V129_EYES.length])')),[7,8,6,6]);
assert.equal(h.run('V129_normalize({skin:99,style:-1}).skin'),2);
h.run("document.getElementById('v129-character-editor').remove=()=>{};V129_draft={...V129_default(),skin:6,style:3,eyes:3,facialHair:1}");
await h.run('V129_save()');
assert.equal(h.run('JSON.parse(localStorage.getItem(localSaveKey())).state.appearance.skin'),6);
h.run('s=JSON.parse(localStorage.getItem(localSaveKey())).state');
assert.match(h.run("personPhoto('player-'+s.name,s.name)"),/v129-portrait/);
assert.doesNotMatch(h.run("personPhoto('artist-other','Other')"),/v129-portrait/);
h.run('V129_draft=V129_default();V129_close()');
assert.equal(h.run('s.appearance.skin'),6);
assert.match(readFileSync('dist/index.html','utf8'),/\.v129-overlay/);
assert.match(readFileSync('dist/game.js','utf8'),/function V129_open/);
console.log('PASS character editor entry, option counts, validation, local persistence, player portrait, cancel isolation and build inclusion');
const online=harness('/');
await online.run('boot()');
online.run("document.getElementById('v129-character-editor').remove=()=>{};V129_draft={...V129_default(),skin:5,hair:7,style:5,eyes:4,facialHair:1}");
await online.run('V129_save()');
online.run('s.appearance=null');
await online.run('boot()');
assert.equal(online.run('s.appearance.skin'),5);
assert.equal(online.run('s.appearance.hair'),7);
assert.equal(online.run('s.appearance.facialHair'),1);
console.log('PASS appearance survives reload through the server save API harness');
